import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import ts from 'typescript';
const source = readFileSync(new URL('../apps/desktop/electron/startup-paths.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { configureDesktopPaths, configurePortableStorage } = await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`);
const options = { packaged: true, executable: 'E:/Metroforge/Portable/MetroForge.exe', resources: 'E:/Metroforge/Portable/resources', developmentRoot: resolve('.') };
const env = {};
const workspace = configureDesktopPaths(options, env);
assert.equal(workspace, resolve('E:/Metroforge/Portable/MetroForgeData'));
assert.equal(env.METROFORGE_RESOURCE_ROOT, join(options.resources, 'metroforge'));
assert.equal(env.METROFORGE_ENV_FILE, join(workspace, '.metroforge', '.env'));
assert.equal(env.METROFORGE_GENERATED_GAMES_DIR, join(workspace, 'GeneratedGames'));
const custom = { METROFORGE_WORKSPACE_DIR: 'E:/Metroforge/Custom', METROFORGE_DATA_DIR: 'E:/Metroforge/Private', METROFORGE_RESOURCE_ROOT: 'E:/Metroforge/Resources' };
configureDesktopPaths(options, custom);
assert.equal(custom.METROFORGE_DATA_DIR, 'E:/Metroforge/Private');
assert.equal(custom.METROFORGE_ENV_FILE, join(custom.METROFORGE_DATA_DIR, '.env'));
assert.throws(() => configureDesktopPaths(options, { METROFORGE_WORKSPACE_DIR: 'relative' }), /absolute/);
assert.throws(() => configureDesktopPaths(options, { METROFORGE_DATA_DIR: 'relative' }), /absolute/);
const devEnv = {};
assert.equal(configureDesktopPaths({ ...options, packaged: false }, devEnv), options.developmentRoot);
assert.deepEqual(devEnv, {});
console.log('Desktop packaged startup path regression PASS');

const portableEnv = { METROFORGE_DATA_DIR: 'E:/Metroforge/Private', TEMP: 'C:/Windows/Temp', HF_HOME: 'C:/Users/Example/.cache' };
const directories = configurePortableStorage(portableEnv);
assert.equal(portableEnv.TEMP, join(portableEnv.METROFORGE_DATA_DIR, 'temp'));
assert.equal(portableEnv.HF_HOME, join(portableEnv.METROFORGE_DATA_DIR, 'cache/huggingface'));
assert.equal(portableEnv.PYTHONDONTWRITEBYTECODE, '1');
assert.equal(directories.length, new Set(directories).size);
assert.ok(directories.every(path => path.startsWith(resolve(portableEnv.METROFORGE_DATA_DIR) + '\\')));
assert.throws(() => configurePortableStorage({}), /absolute data directory/);
console.log('Portable cache and child-process storage regression PASS');
