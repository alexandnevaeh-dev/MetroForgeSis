import assert from 'node:assert/strict';
import {cpSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
const repo=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=join(repo,'reports/game-tests/20261006-player-admission',String(Date.now()));
mkdirSync(output,{recursive:true});
const js=ts.transpileModule(readFileSync(join(repo,'packages/generation/src/stormglass-player-assets.ts'),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {loadStormglassPlayerAssets:load}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const checks=[];
const check=(name,fn)=>{fn();checks.push({name,passed:true});};
const base={idle:{frameCount:8,fps:11,loop:true},run:{frameCount:8,fps:19,loop:true},custom:{frameCount:3,fps:7,loop:false}};
const input=Buffer.from(JSON.stringify(base));
const pack=load(repo,input);
check('eleven original PNGs and fourteen measured clips admitted',()=>{assert.equal(pack.assets.length,11);assert.equal(pack.clips.length,14);assert.equal(pack.productionReady,false);});
check('new idle/run selected and other metadata preserved',()=>{const metadata=JSON.parse(pack.textures.get('assets/characters/player_animations.json'));assert.deepEqual(metadata.custom,base.custom);assert.equal(metadata.run.sourceSheet,'assets/characters/player_run_cape_v2.png');assert.equal(metadata.idle.sourceSheet,'assets/characters/player_idle_cape_v2.png');assert.deepEqual(JSON.parse(input),base);});
check('source PNG bytes preserved',()=>{for(const asset of pack.assets)assert.deepEqual(pack.textures.get(asset.destination),readFileSync(asset.sourcePath));});
const fixture=join(output,'fixture'),packDir=join(fixture,'test-packs',pack.id);
cpSync(join(repo,'test-packs',pack.id),packDir,{recursive:true});
const path=join(packDir,'manifest.json'),original=readFileSync(path),manifest=JSON.parse(original.toString().replace(/^\uFEFF/,''));
const reject=(name,change,pattern)=>check(name,()=>{const value=structuredClone(manifest);change(value);writeFileSync(path,JSON.stringify(value));assert.throws(()=>load(fixture,input),pattern);writeFileSync(path,original);});
reject('path traversal rejected',m=>m.assets[0].source='../outside.png',/path/);
reject('duplicate destination rejected',m=>m.assets.push(m.assets[0]),/duplicate/);
reject('hash tampering rejected',m=>m.assets[0].sha256='0'.repeat(64),/hash mismatch/);
reject('overlapping atlas frames rejected',m=>m.animations.walk.sourceRegions[1][0]=1,/Overlapping/);
reject('out of bounds atlas rejected',m=>m.animations.walk.sourceRegions[0][2]=100000,/out-of-bounds/);
reject('invalid shared scale rejected',m=>m.animations.walk.displayScale=0,/Invalid/);
reject('invalid anchor rejected',m=>m.animations.walk.footAnchorY=99999,/out-of-bounds/);
reject('missing clip rejected',m=>delete m.animations.death,/incomplete/);
reject('false production approval rejected',m=>m.productionReady=true,/Invalid/);
writeFileSync(join(output,'proof.json'),JSON.stringify({passed:true,scope:'Byte preservation, metadata preservation, fail-closed atlas/hash/path admission; not visual approval or app generation',checks},null,2));
console.log(JSON.stringify({passed:true,checks:checks.length,output}));
