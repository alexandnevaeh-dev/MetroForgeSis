import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
const source = resolve('.');
const pointer = join(source, 'reports/game-tests/20261002-quantum-publication/latest.json');
const summary = JSON.parse(readFileSync(pointer, 'utf8'));
assert.equal(summary.status, 'needs-reconciliation');
assert.deepEqual(summary.conflicts.map(value => value.file), ['apps/desktop/src/studio/CreateScreen.tsx']);
const hash = text => createHash('sha256').update(text).digest('hex');
const normalized = path => readFileSync(path, 'utf8').replaceAll('\r\n', '\n');
const file = 'apps/desktop/src/studio/CreateScreen.tsx';
const conflict = normalized(join(summary.output, 'review', file.replaceAll('/', '__') + '.conflict'));
const pattern = /^<<<<<<<[^\n]*\n  }, \[prompt, profile, mode, seed, archetype, refreshProjects, setSelectedPath\]\);\n=======\n(  }, \[title, prompt, profile, mode, parsedSeed, titleError, quantum, archetype, refreshProjects, setSelectedPath\]\);\n)>>>>>>>[^\n]*\n/m;
assert.ok(pattern.test(conflict), 'Only the reviewed callback dependency conflict can be resolved');
const resolved = conflict.replace(pattern, '$1');
assert.ok(!/^(?:<<<<<<<|=======|>>>>>>>)/m.test(resolved));
writeFileSync(join(summary.tree, file), resolved);
summary.files.push(file);
summary.edited.push({ file, resolution: 'Keep new title/seed/Quantum callback dependencies; independently restore title transfer below', stagedSha256: hash(resolved), priorUnpublishedChanges: true });
summary.manualReconciliation = [];
function replace(file, before, after, reason) {
  const path = join(summary.tree, file);
  const text = normalized(path);
  assert.equal(text.split(before).length, 2, 'Ambiguous reconciliation anchor: ' + file);
  const next = text.replace(before, after);
  writeFileSync(path, next);
  if (!summary.files.includes(file)) summary.files.push(file);
  summary.manualReconciliation.push({ file, reason, sha256: hash(next) });
}
replace(file, 'const res = await window.metroforge.generateGame({\n        prompt,', 'const res = await window.metroforge.generateGame({\n        title,\n        prompt,', 'Quantum configuration must receive the entered project title');
replace('packages/generation/src/pipeline.ts', 'export interface GenerateOptions {\n  prompt: string;', 'export interface GenerateOptions {\n  prompt: string;\n  /** Optional project title entered in the desktop commission. */\n  title?: string;', 'Add the public title contract required by dedicated Quantum generation');
replace('apps/desktop/src/studio/metroforge-api.ts', 'generateGame: (opts: {\n    prompt: string;', 'generateGame: (opts: {\n    title?: string;\n    prompt: string;', 'Renderer bridge title contract');
replace('apps/desktop/electron/preload.ts', 'generateGame: (opts: {\n    prompt: string;', 'generateGame: (opts: {\n    title?: string;\n    prompt: string;', 'Normal preload forwards the same optional title without mocks');
replace('apps/desktop/electron/handlers.ts', 'const payload = job.payload as {\n        prompt: string;', 'const payload = job.payload as {\n        title?: string;\n        prompt: string;', 'Typed queue payload retains the project title');
replace('apps/desktop/electron/handlers.ts', "'generate-game',\n    async (\n      event,\n      opts: {\n        prompt: string;", "'generate-game',\n    async (\n      event,\n      opts: {\n        title?: string;\n        prompt: string;", 'Typed IPC request retains the project title');
summary.status = 'ready-for-build';
summary.conflicts = [];
summary.files.sort();
summary.excludedPriorEdits = ['Legacy asynchronous QA worker integration', 'Legacy AI attempt/progress reporting', 'Legacy HD-2D DNA overrides', 'Read-only early generation asset/world previews'];
writeFileSync(join(summary.output, 'review.json'), JSON.stringify(summary, null, 2));
writeFileSync(pointer, JSON.stringify(summary, null, 2));
console.log(JSON.stringify({ status: summary.status, tree: summary.tree, files: summary.files.length, titleContracts: summary.manualReconciliation.length }));
