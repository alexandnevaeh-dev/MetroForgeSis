/** Derive the bounded in-game release QA driver from the verified native GUI fixture. */
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
const repo=resolve('.');assert.match(repo,/^E:[/\\]/i);
const fixture=join(repo,'prototypes/quantum-divergence/tests/WorkbenchTests.gd');
let source=readFileSync(fixture,'utf8').replaceAll('\r\n','\n');
function replace(before,after){assert.equal(source.split(before).length,2,'Fixture adapter anchor changed: '+before);source=source.replace(before,after);}
replace('extends SceneTree','extends Node');
replace('var game\n','var game\n\nfunc _init(owner_world) -> void:\n\tgame = owner_world\n\tprocess_mode = Node.PROCESS_MODE_ALWAYS\n');
replace('func _initialize() -> void:','func _ready() -> void:');
replace('\tgame = load("res://scenes/MinesArtPlayground.tscn").instantiate()\n\troot.add_child(game)','\tcheck(game._package_status().standalone and game._package_status().release and game._package_status().integrity,"native workbench runs inside the verified Windows release PCK")');
replace('root.get_texture().get_image()','get_viewport().get_texture().get_image()');
source=source.replaceAll('await physics_frame','await get_tree().physics_frame').replaceAll('await process_frame','await get_tree().process_frame');
source=source.replace(/ and (not )?paused(?=[,) ])/g,(_match,not)=>' and '+(not||'')+'get_tree().paused');
source=source.replaceAll('\tquit(','\tget_tree().quit(');
replace('var proof := {"passed":passed','var proof := {"package":game._package_status(),"passed":passed');
assert.ok(!/\broot\.|await physics_frame|await process_frame| and (?:not )?paused[,) ]/.test(source));
const output=join(repo,'prototypes/quantum-divergence/scripts/WorkbenchRunDriver.gd');
const expected='# Generated by scripts/build-quantum-workbench-probe.mjs; same actions/assertions as WorkbenchTests.gd.\n'+source;
if(process.argv.includes('--check')) assert.equal(readFileSync(output,'utf8'),expected,'In-package driver no longer matches the GUI fixture');
else writeFileSync(output,expected);
console.log(JSON.stringify({output,scope:'Bounded game-owned input QA only; invoked explicitly with --workbench-probe'}));
