import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdtempSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
const [stageArg,imageArg,weightsArg]=process.argv.slice(2);
if(!stageArg||!imageArg||!weightsArg)throw Error('Supply portable directory, source PNG, and U2-Net weights');
const stage=resolve(stageArg),source=resolve(imageArg),weights=resolve(weightsArg);
if(![stage,source,weights].every(p=>/^E:[\\/]/i.test(p)))throw Error('Validation files must remain on E:');
process.env.METROFORGE_RESOURCE_ROOT=join(stage,'resources/metroforge');
process.env.METROFORGE_U2NET_WEIGHTS_PATH=weights;
const {DiffusersProvider}=await import(pathToFileURL(join(stage,'resources/app/node_modules/@metroforge/assets/dist/providers/diffusers.js')).href);
const provider=new DiffusersProvider({device:'cuda'});
const result=await provider.segmentForeground(readFileSync(source));
assert.equal(result.ok,true,result.error);assert.equal(result.device,'cuda');assert.ok(result.buffer?.length);assert.ok(result.occupancy>0&&result.occupancy<1);
const out=mkdtempSync('E:/Metroforge/Recovery-Audit/packaged-isolation-');
writeFileSync(join(out,'isolated.png'),result.buffer);
const {buffer,...metadata}=result;
writeFileSync(join(out,'result.json'),JSON.stringify({passed:true,stage,source,metadata,scope:'Actual packaged provider and Python worker with local CUDA U2-Net; not artwork approval'},null,2));
console.log('PASS packaged CUDA isolation:',out);