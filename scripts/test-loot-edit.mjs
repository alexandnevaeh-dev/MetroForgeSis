import {mkdtempSync,mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {readEditableLoot,saveEditableLoot,createEditableLoot,saveEditableLootSource} from '../packages/generation/dist/loot-edit-service.js';
const dir=mkdtempSync('E:/Metroforge/Recovery-Audit/loot-edit-');
for(const folder of ['loot','items','enemies']) mkdirSync(`${dir}/data/${folder}`,{recursive:true});
const table={id:'abbey',name:'Abbey',custom:'keep',entries:[{itemId:'plate',chance:0.1,minQuantity:1,maxQuantity:1,customEffect:'keep'}]};
const file=dir+'/data/loot/loot_tables.json';
writeFileSync(file,JSON.stringify({version:2,tables:[table,{...table,id:'other'}]}));
writeFileSync(dir+'/data/items/items.json',JSON.stringify({items:[{id:'plate'}]}));
writeFileSync(dir+'/data/enemies/enemies.json',JSON.stringify({enemies:[{id:'guard',lootTableId:'abbey'}]}));
const opened=readEditableLoot(dir);
const edited={...table,entries:[{itemId:'plate',chance:0.7,minQuantity:2,maxQuantity:4}]};
const saved=saveEditableLoot(dir,edited,opened.revision);
const result=JSON.parse(readFileSync(file,'utf8'));
assert.equal(result.tables[0].entries[0].chance,0.7);assert.equal(result.tables[0].entries[0].customEffect,'keep');
assert.equal(result.tables[0].custom,'keep');assert.equal(result.version,2);assert.deepEqual(result.tables[1],{...table,id:'other'});
assert.deepEqual(JSON.parse(readFileSync(saved.backup,'utf8')).tables[0],table);
assert.throws(()=>saveEditableLoot(dir,table,opened.revision),/changed/);
const before=readFileSync(file,'utf8');
assert.throws(()=>saveEditableLoot(dir,{...table,entries:[{...table.entries[0],itemId:'missing'}]},saved.revision),/unknown item/);
assert.throws(()=>saveEditableLoot(dir,{...table,entries:[{...table.entries[0],chance:2}]},saved.revision));
assert.equal(readFileSync(file,'utf8'),before);
writeFileSync(dir+'/data/items/items.json',JSON.stringify({items:[{id:'plate',name:'Changed'}]}));
assert.throws(()=>saveEditableLoot(dir,table,saved.revision),/changed/);
const fresh=readEditableLoot(dir);
const cleared=saveEditableLoot(dir,{...table,entries:[]},fresh.revision);
assert.equal(readEditableLoot(dir).tables[0].entries.length,0);assert.equal(cleared.restartRequired,true);
console.log('PASS loot edit/save, metadata, backups, stale table/item revisions, invalid edit preservation, empty drops');

const runtime=dir+'/Assets/StreamingAssets/data/loot/loot_tables.json';
mkdirSync(dir+'/Assets/StreamingAssets/data/loot',{recursive:true});
writeFileSync(runtime,readFileSync(file,'utf8'));
const mirrored=readEditableLoot(dir);
const mirroredSave=saveEditableLoot(dir,edited,mirrored.revision);
assert.equal(mirroredSave.runtimeSynchronized,true);
assert.equal(readFileSync(file,'utf8'),readFileSync(runtime,'utf8'));
assert.equal(mirroredSave.restartRequired,true);
const mirrorBefore=readFileSync(runtime,'utf8');
const changedRevision=readEditableLoot(dir).revision;
writeFileSync(runtime,mirrorBefore+'\n');
assert.throws(()=>saveEditableLoot(dir,table,changedRevision),/changed/);
writeFileSync(runtime,JSON.stringify({tables:[]}));
assert.throws(()=>readEditableLoot(dir),/copies differ/);
assert.equal(readFileSync(file,'utf8'),mirrorBefore);
console.log('PASS Unity loot mirror save, restart, stale runtime revision and divergent-copy protection');

// Runtime references must agree with the editor, and participate in stale-edit detection.
writeFileSync(runtime, mirrorBefore);
for (const relative of ['items/items.json', 'enemies/enemies.json']) {
  const target=dir+'/Assets/StreamingAssets/data/'+relative;
  mkdirSync(target.slice(0,target.lastIndexOf('/')),{recursive:true});
  const source=readFileSync(dir+'/data/'+relative,'utf8');
  writeFileSync(target,source);
  const state=readEditableLoot(dir);
  writeFileSync(target,source+'\n');
  assert.throws(()=>saveEditableLoot(dir,edited,state.revision),/changed/);
  writeFileSync(target,relative.startsWith('items')?'{"items":[]}':'{"enemies":[]}');
  assert.throws(()=>readEditableLoot(dir),/referenced runtime catalog differs/);
  assert.equal(readFileSync(file,'utf8'),mirrorBefore);
  assert.equal(readFileSync(runtime,'utf8'),mirrorBefore);
  writeFileSync(target,source);
}
console.log('PASS runtime item/enemy reference parity and concurrent-change protection');

const beforeCreate=readEditableLoot(dir);
const added={id:'crypt_rare',name:'Crypt rare equipment',entries:[{itemId:'plate',chance:0.25,minQuantity:1,maxQuantity:2}]};
const created=createEditableLoot(dir,added,beforeCreate.revision);
assert.equal(created.runtimeSynchronized,true);
assert.deepEqual(readEditableLoot(dir).tables.at(-1),added);
assert.deepEqual(readEditableLoot(dir).tables.slice(0,-1),beforeCreate.tables);
assert.equal(readFileSync(file,'utf8'),readFileSync(runtime,'utf8'));
assert.deepEqual(JSON.parse(readFileSync(created.backup,'utf8')).tables,beforeCreate.tables);
assert.throws(()=>createEditableLoot(dir,added,created.revision),/already exists/);
assert.throws(()=>createEditableLoot(dir,{...added,id:'stale'},beforeCreate.revision),/changed/);
const stable=readFileSync(file,'utf8');
assert.throws(()=>createEditableLoot(dir,{...added,id:'invalid',entries:[{...added.entries[0],itemId:'missing'}]},created.revision),/unknown item/);
assert.equal(readFileSync(file,'utf8'),stable);
console.log('PASS loot creation, mirror, preservation, backup, duplicate and stale/invalid rejection');

const assignmentState=readEditableLoot(dir);
assert.equal(assignmentState.sources[0].id,'guard');
const assigned=saveEditableLootSource(dir,'guard','crypt_rare',assignmentState.revision);
assert.equal(readEditableLoot(dir).sources[0].lootTableId,'crypt_rare');
const enemyFile=dir+'/data/enemies/enemies.json';
const enemyRuntime=dir+'/Assets/StreamingAssets/data/enemies/enemies.json';
assert.equal(readFileSync(enemyFile,'utf8'),readFileSync(enemyRuntime,'utf8'));
assert.equal(JSON.parse(readFileSync(assigned.backup,'utf8')).enemies[0].lootTableId,'abbey');
assert.throws(()=>saveEditableLootSource(dir,'guard','missing',assigned.revision),/unknown table/);
assert.throws(()=>saveEditableLootSource(dir,'missing','abbey',assigned.revision),/existing enemy/);
assert.throws(()=>saveEditableLootSource(dir,'guard',null,assignmentState.revision),/changed/);
const clearedSource=saveEditableLootSource(dir,'guard',null,assigned.revision);
assert.equal(readEditableLoot(dir).sources[0].lootTableId,undefined);
assert.equal(clearedSource.runtimeSynchronized,true);
assert.equal(readFileSync(enemyFile,'utf8'),readFileSync(enemyRuntime,'utf8'));
console.log('PASS enemy loot assignment, clear, runtime sync, backup and invalid/stale protection');
